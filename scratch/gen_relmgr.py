# 生成 scripts/RelationshipManager.gd（tab 缩进，保证不与 GameManager 的 4 空格混用）
import io, os

lines = []
def L(indent, text):
    lines.append(("\t" * indent) + text)

L(0, "extends Node")
L(0, "")
L(0, "# ═══════════════════════════════════════════════════════════════")
L(0, "# ── RelationshipManager ───────────────────────────────────────")
L(0, "# 关系状态机：状态 = 好感度的纯函数 + 冷战覆盖态")
L(0, "# 状态缓存留守 GameManager.relationship_state（经门面访问）")
L(0, "# ═══════════════════════════════════════════════════════════════")
L(0, "")
L(0, "# 状态定义（id / 中文 / 颜色 / 好感下限）")
L(0, "const REL_STATES = {")
L(1, '"stranger":    {"label": "陌生", "color": "#9ca3af", "min_fav": 0},')
L(1, '"acquaintance":{"label": "熟悉", "color": "#60a5fa", "min_fav": 15},')
L(1, '"friend":      {"label": "朋友", "color": "#34d399", "min_fav": 30},')
L(1, '"close":       {"label": "暧昧", "color": "#f472b6", "min_fav": 60},')
L(1, '"crush":       {"label": "心动", "color": "#fb7185", "min_fav": 85},')
L(1, '"cold":        {"label": "冷战", "color": "#ef4444", "min_fav": -1},')
L(0, "}")
L(0, "")
L(0, "# 上升态顺序（用于升级/降级判断；cold 不在其中，作为覆盖态单独处理）")
L(0, 'const REL_ORDER = ["stranger", "acquaintance", "friend", "close", "crush"]')
L(0, "")
L(0, "signal rel_state_changed(char_id: String, prev_state: String, new_state: String)")
L(0, "")
L(0, "func _rel_index(state: String) -> int:")
L(1, "return REL_ORDER.find(state)")
L(0, "")
L(0, "# ── 由好感推导基础状态（不含冷战覆盖）────────────────────────")
L(0, "func _derive_base_state(char_id: String) -> String:")
L(1, "var fav = GameManager.favorability.get(char_id, 0)")
L(1, 'var result = "stranger"')
L(1, "for s in REL_ORDER:")
L(2, "if fav >= REL_STATES[s][\"min_fav\"]:")
L(3, "result = s")
L(1, "return result")
L(0, "")
L(0, "# ── 重算单个角色状态（含冷战覆盖 + 升级提示）────────────────")
L(0, "func recompute_rel_state(char_id: String, silent: bool = false):")
L(1, 'var prev = GameManager.relationship_state.get(char_id, "stranger")')
L(1, "var now = _derive_base_state(char_id)")
L(1, 'if GameManager.flags.has("rel_cold_" + char_id):')
L(2, 'now = "cold"')
L(1, "GameManager.relationship_state[char_id] = now")
L(1, "rel_state_changed.emit(char_id, prev, now)")
L(1, "if not silent and _rel_index(now) > _rel_index(prev):")
L(2, "var char_name = GameManager.char_meta.get(char_id, {}).get(\"name\", char_id)")
L(2, 'GameManager.show_toast.emit("💞 你和 %s 的关系进入了『%s』阶段！" % [char_name, REL_STATES[now]["label"]])')
L(0, "")
L(0, "# ── 重算所有角色 ──────────────────────────────────────────────")
L(0, "func recompute_all_states(silent: bool = false):")
L(1, "for char_id in GameManager.favorability.keys():")
L(2, "recompute_rel_state(char_id, silent)")
L(0, "")
L(0, "# ── 查询门面 ──────────────────────────────────────────────────")
L(0, "func get_rel_state(char_id: String) -> String:")
L(1, "if GameManager.relationship_state.has(char_id):")
L(2, "return GameManager.relationship_state[char_id]")
L(1, "return _derive_base_state(char_id)")
L(0, "")
L(0, "func get_rel_state_display(char_id: String) -> Dictionary:")
L(1, "var st = get_rel_state(char_id)")
L(1, 'return REL_STATES.get(st, REL_STATES["stranger"])')
L(0, "")
L(0, "# ── 冷战：进入 ────────────────────────────────────────────────")
L(0, "func enter_cold_war(char_id: String):")
L(1, 'if GameManager.flags.has("rel_cold_" + char_id):')
L(2, "return  # 已在冷战，避免重复扣好感")
L(1, "var char_name = GameManager.char_meta.get(char_id, {}).get(\"name\", char_id)")
L(1, 'GameManager.set_flag("rel_cold_" + char_id, true)')
L(1, "GameManager.favorability[char_id] = clampi(GameManager.favorability[char_id] - 10, 0, 100)")
L(1, 'var prev = GameManager.relationship_state.get(char_id, "stranger")')
L(1, 'GameManager.relationship_state[char_id] = "cold"')
L(1, 'GameManager.show_toast.emit("❄️ 你和 %s 陷入了冷战……" % char_name)')
L(1, 'rel_state_changed.emit(char_id, prev, "cold")')
L(0, "")
L(0, "# ── 冷战：挽回 ────────────────────────────────────────────────")
L(0, "func recover_from_cold(char_id: String):")
L(1, 'if not GameManager.flags.has("rel_cold_" + char_id):')
L(2, "return")
L(1, "var char_name = GameManager.char_meta.get(char_id, {}).get(\"name\", char_id)")
L(1, 'GameManager.set_flag("rel_cold_" + char_id, false)')
L(1, 'var prev = "cold"')
L(1, "var now = _derive_base_state(char_id)")
L(1, "GameManager.relationship_state[char_id] = now")
L(1, 'GameManager.show_toast.emit("🌸 你和 %s 和好了。" % char_name)')
L(1, 'rel_state_changed.emit(char_id, prev, now)')

content = "\n".join(lines) + "\n"
out_path = os.path.join(os.path.dirname(__file__), "..", "scripts", "RelationshipManager.gd")
out_path = os.path.abspath(out_path)
with io.open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(content)
print("written:", out_path, "lines:", len(lines))
# 自检：不应出现前导空格（缩进必须全是 tab）
bad = [i+1 for i, ln in enumerate(content.split("\n")) if ln[:1] in (" ",) and ln.strip() != ""]
print("lines starting with space:", bad)
